export function formatLocalizedSbtTier(tier: SbtTier, multiplier: number, copy: AppCopy): string {
  if (tier === 'none') return copy.sbt.tiers.none
  return `${copy.sbt.tiers[tier]} x${multiplier}`
}

export function packLabel(pack: PackKey, copy: AppCopy): string {
  return copy.packs[pack]
}
